// =====================================================
// SHOW ROADMAP MODAL
// =====================================================

function showRoadmap(
    career,
    matchedSkills,
    skillsToDevelop
) {

    // =============================================
    // GET MODAL ELEMENTS
    // =============================================

    const modal =
        document.getElementById(
            "roadmapModal"
        );


    const title =
        document.getElementById(
            "roadmapCareerName"
        );


    const description =
        document.getElementById(
            "roadmapDescription"
        );


    const icon =
        document.getElementById(
            "roadmapIcon"
        );


    const content =
        document.getElementById(
            "roadmapContent"
        );


    // =============================================
    // CHECK MODAL
    // =============================================

    if (!modal) {

        console.error(
            "roadmapModal not found."
        );

        return;

    }


    if (!title || !description || !icon || !content) {

        console.error(
            "Roadmap modal elements are missing."
        );

        return;

    }


    // =============================================
    // GET ROADMAP
    // =============================================

    const roadmap =
        careerRoadmaps[career];


    // =============================================
    // CAREER NOT FOUND
    // =============================================

    if (!roadmap) {

        title.textContent =
            career;


        description.textContent =
            "Roadmap information is not available yet.";


        icon.className =
            getCareerIcon(
                career
            );


        content.innerHTML = `

            <div class="roadmap-fallback">

                <i class="fa-solid fa-road"></i>

                <p>

                    Roadmap for

                    <strong>
                        ${career}
                    </strong>

                    is currently being prepared.

                </p>

            </div>

        `;


        openRoadmapModal();

        return;

    }


    // =============================================
    // HEADER
    // =============================================

    title.textContent =
        career;


    description.textContent =
        roadmap.description || "";


    icon.className =
        roadmap.icon ||
        getCareerIcon(career);


    // =============================================
    // NORMALIZE SKILLS
    // =============================================

    matchedSkills =
        Array.isArray(matchedSkills)
            ? matchedSkills
            : [];


    skillsToDevelop =
        Array.isArray(skillsToDevelop)
            ? skillsToDevelop
            : [];


    const normalizedMatched =
        matchedSkills.map(
            skill =>
                String(skill)
                    .toLowerCase()
                    .trim()
        );


    const normalizedDevelop =
        skillsToDevelop.map(
            skill =>
                String(skill)
                    .toLowerCase()
                    .trim()
        );


    // =============================================
    // RENDER
    // =============================================

    let roadmapHTML = "";

    if (roadmap.type === "single") {

        roadmapHTML =
            renderRoadmapStages(
                roadmap.stages,
                normalizedMatched,
                normalizedDevelop
            );


        // Backend technology options

        if (career === "Backend Developer") {

            roadmapHTML +=
                renderBackendTechnologyOptions();

        }


        // Frontend technology options

        if (career === "Frontend Developer") {

            roadmapHTML +=
                renderFrontendTechnologyOptions();

        }

    }
    else if (roadmap.type === "combined") {

        roadmapHTML =
            renderCombinedRoadmap(
                roadmap.tracks,
                normalizedMatched,
                normalizedDevelop
            );

    }
    else {

        roadmapHTML = `

        <div class="roadmap-fallback">

            <p>
                Invalid roadmap type.
            </p>

        </div>

    `;

    }

    // =============================================
    // LEGEND
    // =============================================

    roadmapHTML += `

        <div class="roadmap-legend mt-4">

            <span class="legend-completed">

                <i class="fa-solid fa-circle-check"></i>

                Completed

            </span>


            <span class="legend-next">

                <i class="fa-solid fa-arrow-right"></i>

                Next Step

            </span>

        </div>

    `;


    content.innerHTML =
        roadmapHTML;


    // =============================================
    // OPEN MODAL
    // =============================================

    openRoadmapModal();

}


// =====================================================
// OPEN ROADMAP MODAL
// =====================================================

function openRoadmapModal() {

    const modal =
        document.getElementById(
            "roadmapModal"
        );


    if (!modal) return;


    // Bootstrap modal
    if (
        typeof bootstrap !== "undefined"
    ) {

        const bsModal =
            bootstrap.Modal.getOrCreateInstance(
                modal
            );

        bsModal.show();

        return;

    }


    // Fallback
    modal.classList.remove(
        "d-none"
    );


    modal.style.display =
        "flex";

}


