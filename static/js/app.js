// =====================================================
// RECOMMEND CAREER
// =====================================================

function recommendCareer() {

    let age =
        document.getElementById(
            "age"
        ).value;


    let education =
        $("#education").val();


    // =================================================
    // VALIDATION
    // =================================================

    if (!age) {

        alert(
            "Please enter your age"
        );

        return;

    }


    if (!education) {

        alert(
            "Please select your education"
        );

        return;

    }


    if (
        selectedSkills.length === 0
    ) {

        alert(
            "Please select at least one skill"
        );

        return;

    }


    if (
        selectedInterests.length === 0
    ) {

        alert(
            "Please select at least one interest"
        );

        return;

    }


    // =================================================
    // DATA
    // =================================================

    let data = {

        age:
            parseInt(age),

        education:
            education,

        skills:
            selectedSkills,

        interests:
            selectedInterests

    };


    // =================================================
    // LOADING
    // =================================================

    $("#loading")
        .removeClass("d-none");


    // =================================================
    // API
    // =================================================

    fetch(
        "/recommend",
        {

            method: "POST",

            headers: {

                "Content-Type":
                    "application/json"

            },

            body:
                JSON.stringify(data)

        }
    )

        .then(
            response =>
                response.json()
        )

        .then(
            result => {

                $("#loading")
                    .addClass("d-none");


                if (
                    result.success
                ) {

                    showResult(
                        result.recommendations
                    );

                }

                else {

                    alert(
                        result.message
                    );

                }

            }
        )

        .catch(
            error => {

                console.error(
                    error
                );

                $("#loading")
                    .addClass("d-none");

                alert(
                    "API Error"
                );

            }
        );

}


