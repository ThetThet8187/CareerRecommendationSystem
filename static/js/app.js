// RENDER SINGLE ROADMAP
// =====================================================

function renderRoadmapStages(
    stages,
    matchedSkills,
    skillsToDevelop
) {

    if (
        !stages ||
        stages.length === 0
    ) {

        return `

            <div class="roadmap-fallback">

                <i class="fa-solid fa-road"></i>

                <p>
                    No roadmap stages available.
                </p>

            </div>

        `;

    }


    return stages.map(
        (stage, index) => {

            return `

                <div class="roadmap-stage">


                    <!-- NUMBER -->

                    <div class="roadmap-number">

                        ${index + 1}

                    </div>


                    <!-- CONTENT -->

                    <div class="roadmap-stage-content">


                        <h5 class="roadmap-stage-title">

                            ${stage.title}

                        </h5>


                        <div class="roadmap-skills">

                            ${(stage.skills || [])
                    .map(
                        skill => {

                            const skillName =
                                String(skill)
                                    .toLowerCase()
                                    .trim();


                            // =================================
                            // MATCH CHECK
                            // =================================

                            const isMatched =
                                matchedSkills.some(
                                    matched => {

                                        const m =
                                            String(matched)
                                                .toLowerCase()
                                                .trim();


                                        return (

                                            m === skillName ||

                                            m.includes(
                                                skillName
                                            ) ||

                                            skillName.includes(
                                                m
                                            )

                                        );

                                    }
                                );


                            // =================================
                            // COMPLETED
                            // =================================

                            if (
                                isMatched
                            ) {

                                return `

                                                    <div
                                                        class="roadmap-skill roadmap-completed"
                                                    >

                                                        <div>

                                                            <i class="fa-solid fa-circle-check"></i>

                                                            <span>
                                                                ${skill}
                                                            </span>

                                                        </div>


                                                        <small>

                                                            Completed

                                                        </small>

                                                    </div>

                                                `;

                            }


                            // =================================
                            // NEXT
                            // =================================

                            return `

                                                <div
                                                    class="roadmap-skill roadmap-next"
                                                >

                                                    <div>

                                                        <i class="fa-solid fa-arrow-right"></i>

                                                        <span>
                                                            ${skill}
                                                        </span>

                                                    </div>


                                                    <small>

                                                        Next Step

                                                    </small>

                                                </div>

                                            `;

                        }
                    )
                    .join("")

                }

                        </div>

                    </div>

                </div>

            `;

        }
    ).join("");

}

