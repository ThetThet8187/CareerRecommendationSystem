let selectedSkills = [];

let selectedInterests = [];


// =====================================================
// INITIALIZE SELECT2
// =====================================================

$(document).ready(function () {

    $("#skillSelect").select2({

        placeholder: "Search or select skills",

        allowClear: true

    });


    $("#interestSelect").select2({

        placeholder: "Search or select interests",

        allowClear: true

    });


    // =================================================
    // SKILL CHANGE
    // =================================================

    $("#skillSelect").on(
        "select2:select",
        function (e) {

            let value =
                e.params.data.id;


            if (value === "Other") {

                $("#otherSkillBox")
                    .removeClass("d-none");

            }

            else {

                addSkill(value);

            }


            $("#skillSelect")
                .val(null)
                .trigger("change");

        }
    );


    // =================================================
    // INTEREST CHANGE
    // =================================================

    $("#interestSelect").on(
        "select2:select",
        function (e) {

            let value =
                e.params.data.id;


            if (value === "Other") {

                $("#otherInterestBox")
                    .removeClass("d-none");

            }

            else {

                addInterest(value);

            }


            $("#interestSelect")
                .val(null)
                .trigger("change");

        }
    );


    // =================================================
    // OTHER SKILL
    // =================================================

    $("#otherSkillInput").keypress(
        function (e) {

            if (e.which === 13) {

                let value =
                    $(this)
                        .val()
                        .trim();


                if (value) {

                    addSkill(value);

                    $(this).val("");

                }

            }

        }
    );


    // =================================================
    // OTHER INTEREST
    // =================================================

    $("#otherInterestInput").keypress(
        function (e) {

            if (e.which === 13) {

                let value =
                    $(this)
                        .val()
                        .trim();


                if (value) {

                    addInterest(value);

                    $(this).val("");

                }

            }

        }
    );

});


// =====================================================
// ADD SKILL
// =====================================================

function addSkill(skill) {

    if (
        skill &&
        !selectedSkills.includes(skill)
    ) {

        selectedSkills.push(skill);

        renderSkills();

    }

}


// =====================================================
// RENDER SKILLS
// =====================================================

function renderSkills() {

    let box =
        document.getElementById(
            "selectedSkills"
        );


    if (!box) return;


    box.innerHTML = "";


    selectedSkills.forEach(
        (skill, index) => {

            box.innerHTML += `

                <span class="badge bg-primary me-2 p-2">

                    ${skill}

                    <span
                        style="cursor:pointer"
                        onclick="removeSkill(${index})"
                    >

                        ❌

                    </span>

                </span>

            `;

        }
    );

}


// =====================================================
// REMOVE SKILL
// =====================================================

function removeSkill(index) {

    selectedSkills.splice(index, 1);

    renderSkills();

}


// =====================================================
// ADD INTEREST
// =====================================================

function addInterest(value) {

    if (
        value &&
        !selectedInterests.includes(value)
    ) {

        selectedInterests.push(value);

        renderInterests();

    }

}


