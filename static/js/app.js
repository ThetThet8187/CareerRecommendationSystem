// =====================================================
// OPEN JOB SOURCE
// =====================================================

function openJobSource(source) {

    const modal =
        document.getElementById(
            "jobSourceModal"
        );


    const career =
        modal?.dataset.career || "";


    let keyword =
        career
            .trim()
            .replace(
                /\s+/g,
                " "
            );


    const encodedKeyword =
        encodeURIComponent(
            keyword
        );


    let url = "";


    // =============================================
    // LINKEDIN
    // =============================================

    if (
        source === "linkedin"
    ) {

        url =
            "https://www.linkedin.com/jobs/search/?keywords=" +
            encodedKeyword;

    }


    // =============================================
    // JOBNET
    // =============================================

    else if (
        source === "jobnet"
    ) {

        url =
            "https://www.jobnet.com.mm/jobs?kw=" +
            encodedKeyword;

    }


    // =============================================
    // JOBSPACE
    // =============================================

    else if (
        source === "jobspace"
    ) {

        url =
            "https://jobspace.com.mm/find-jobs?search=" +
            encodedKeyword;

    }


    // =============================================
    // INVALID
    // =============================================

    if (!url) {

        console.error(
            "Invalid job source:",
            source
        );

        return;

    }


    // =============================================
    // OPEN
    // =============================================

    window.open(
        url,
        "_blank"
    );


    closeJobSourceModal();

}


